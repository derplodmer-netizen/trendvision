def default(lang: str, key: str) -> str:
    return DEFAULTS.get(lang, DEFAULTS["ru"]).get(key) or DEFAULTS["ru"][key]


async def get_text(s, lang: str, key: str, ab: str = "a", **fmt) -> str:
    keys = [f"{lang}:{key}:{ab}", f"{lang}:{key}"]
    rows = (await s.execute(select(TextOverride).where(TextOverride.key.in_(keys)))).scalars().all()
    found = {r.key: r.body for r in rows}
    body = found.get(keys[0]) or found.get(keys[1]) or default(lang, key)
    try:
        return body.format(**fmt) if fmt else body
    except (KeyError, IndexError, ValueError):
        return body          # an admin typo in a placeholder must not break the step


def text_keys() -> list[str]:
    return list(DEFAULTS["ru"].keys())
